-- H2 equivalents of the Railway relationships; these are test tables, not new entities.
CREATE TABLE IF NOT EXISTS public."User_owns_card" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid INTEGER REFERENCES public."User"(id),
    cardid INTEGER,
    "value" INTEGER,
    CONSTRAINT fk_user_owns_card_card FOREIGN KEY (cardid)
        REFERENCES public."Card"(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public."Deck" (
    id INTEGER PRIMARY KEY,
    userid INTEGER REFERENCES public."User"(id),
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public."Card_in_deck" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cardid INTEGER,
    deckid INTEGER REFERENCES public."Deck"(id),
    userid INTEGER,
    type TEXT,
    CONSTRAINT fk_card_in_deck_card FOREIGN KEY (cardid)
        REFERENCES public."User_owns_card"(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public."Wins" (
    id INTEGER PRIMARY KEY,
    winninguser INTEGER REFERENCES public."User"(id),
    losinguser INTEGER REFERENCES public."User"(id),
    winningcard INTEGER,
    losingcard INTEGER,
    CONSTRAINT fk_wins_winning_card FOREIGN KEY (winningcard)
        REFERENCES public."User_owns_card"(id) ON DELETE SET NULL,
    CONSTRAINT fk_wins_losing_card FOREIGN KEY (losingcard)
        REFERENCES public."User_owns_card"(id) ON DELETE SET NULL
);
