-- Initial schema for a new, empty LOCAL PostgreSQL volume.
-- Mirrors Railway's table names, integer IDs, and card deletion rules.
CREATE TABLE IF NOT EXISTS public."User" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    displayname TEXT NOT NULL,
    password TEXT,
    isadmin BOOLEAN NOT NULL DEFAULT FALSE,
    google_subject TEXT NOT NULL,
    CONSTRAINT user_google_subject_unique UNIQUE (google_subject)
);

CREATE TABLE IF NOT EXISTS public."Card" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    imgurl TEXT,
    description TEXT,
    type TEXT NOT NULL,
    author INTEGER,
    CONSTRAINT fk_card_author FOREIGN KEY (author) REFERENCES public."User"(id)
);

CREATE TABLE IF NOT EXISTS public."User_owns_card" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid INTEGER,
    cardid INTEGER,
    value INTEGER,
    CONSTRAINT fk_user_owns_card_user FOREIGN KEY (userid) REFERENCES public."User"(id),
    CONSTRAINT fk_user_owns_card_card FOREIGN KEY (cardid)
        REFERENCES public."Card"(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public."Deck" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid INTEGER,
    name TEXT NOT NULL,
    CONSTRAINT fk_deck_user FOREIGN KEY (userid) REFERENCES public."User"(id)
);

CREATE TABLE IF NOT EXISTS public."Card_in_deck" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cardid INTEGER,
    deckid INTEGER,
    userid INTEGER,
    type TEXT,
    CONSTRAINT fk_card_in_deck_card FOREIGN KEY (cardid)
        REFERENCES public."User_owns_card"(id) ON DELETE CASCADE,
    CONSTRAINT fk_card_in_deck_deck FOREIGN KEY (deckid) REFERENCES public."Deck"(id)
);

CREATE TABLE IF NOT EXISTS public."Wins" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    winninguser INTEGER,
    losinguser INTEGER,
    winningcard INTEGER,
    losingcard INTEGER,
    CONSTRAINT fk_wins_winning_user FOREIGN KEY (winninguser) REFERENCES public."User"(id),
    CONSTRAINT fk_wins_losing_user FOREIGN KEY (losinguser) REFERENCES public."User"(id),
    CONSTRAINT fk_wins_winning_card FOREIGN KEY (winningcard)
        REFERENCES public."User_owns_card"(id) ON DELETE SET NULL,
    CONSTRAINT fk_wins_losing_card FOREIGN KEY (losingcard)
        REFERENCES public."User_owns_card"(id) ON DELETE SET NULL
);
